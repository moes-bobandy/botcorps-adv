#!/usr/bin/env python3
"""Writes scripts/tour.txt. Portrait pterm keyboard geometry from botcorps_ui.cpp pt_hit():
PT box 10,249 220x53 -> keys at x=14+col*21 (w 20), y=265+row*6 (h 5)."""
import os
def key(c, r, span=1): return (14 + c * 21 + (21 * span - 1) // 2, 267 + r * 6)
keys = {}
for r, s in enumerate(["1234567890", "qwertyuiop", "asdfghjkl"]):
    for c, ch in enumerate(s): keys[ch] = key(c, r)
for c, ch in enumerate("zxcvbnm"): keys[ch] = key(c + 1, 3)
keys[' '] = key(2, 4, 6); OK = key(8, 4, 2); BACK = key(0, 4, 2)
def typ(w): return [f"tap {keys[ch][0]} {keys[ch][1]}" for ch in w]
L = ["# Full tour (generated by tools/mktour.py): boot -> hub -> chips -> terminal (glossary, keyboard) -> Defend game -> Control + every UI COLOR",
     "shot 00-boot-t100", "until 1500", "shot 01-boot-t1500", "until 3000", "shot 02-boot-t3000",
     "until 9000", "shot 03-hub",
     "tap 24 54", "wait 400", "shot 04-chip-bot0-scan",          # bot 0 = WIFI -> wifi-radar
     "tap 146 12", "wait 400", "shot 05-back-hub",               # crown = back
     "tap 120 114", "wait 400", "shot 06-chip-gibson-scan",
     "tap 146 12", "wait 400",
     "tap 177 12", "wait 600", "shot 07-terminal",               # >_ in top bar
     "tap 171 287", "wait 300", "shot 08-terminal-glossary",     # glossary button
     "tap 208 294", "wait 300",                                  # list BACK
     "tap 208 287", "wait 300", "shot 09-terminal-keyboard"]     # abc button
L += typ("scan") + ["wait 300", "shot 10-terminal-typed-scan",
     f"tap {BACK[0]} {BACK[1]}", "wait 300", "shot 11-terminal-kb-closed",
     "tap 146 12", "wait 600", "shot 12-after-crown-tap-still-terminal",              # observed: one crown tap here does not leave Terminal
     "tap 208 287", "wait 300", "shot 13-terminal-keyboard-again"]
L += typ("defend") + ["wait 200", "shot 14-typed-defend",
     f"tap {OK[0]} {OK[1]}", "wait 600", "shot 15-game-defend",
     "wait 3000", "shot 16-game-defend-3s",
     "tap 146 12", "wait 600", "tap 146 12", "wait 600", "shot 17-back-from-game",
     "tap 138 221", "wait 300", "shot 18-hub-control-plate-selected",
     "tap 138 221", "wait 600", "shot 19-control"]
for i in range(11):
    L += ["tap 151 63", "wait 400", f"shot {20+i}-control-color-tap{i+1}"]
p = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "scripts", "tour.txt")
open(p, "w").write("\n".join(L) + "\n")
print("wrote", p)
