"""Trace the GIBSON v8 board art (full screen, outside rain windows and the plate interior x34-179 y272-305) from the ref clip as per-segment
mode images, keep only pixels the firmware base render does not already produce, and emit
delta patches (RGB565) for gib_v8_art.inc. Ref: g8q/qNNNN.png (palette-snapped 240x320 frames)."""
import numpy as np, sys
from PIL import Image
H=320
OVL=[(34,120),(379,432)]
isov=lambda f: any(a<=f<=b for a,b in OVL)
win=[(32,128,72,24),(176,128,32,32),(176,200,32,32),(32,232,72,8),(32,240,192,8),(32,248,176,8)]
M=np.ones((H,240),bool)
for x,y,w,h in win: M[y:y+h,x:x+w]=False
M[272:306,34:180]=False                     # plate interior: procedural v8_plate (cleared after the art layer)
P=np.load('P320.npy')                      # ref, frame f at P[f-1]
def load(f):
    a=np.array(Image.open('hb/gp/out/base/f%04d.png'%f).convert('RGB'))[:H].astype(np.int32)
    return (a[...,0]<<16)|(a[...,1]<<8)|a[...,2]
B=np.stack([load(f) for f in range(1,631)])
T=int(sys.argv[1]) if len(sys.argv)>1 else 24
# segments over non-overlay frames
segs=[]; f=1
while f<=630:
    if isov(f): f+=1; continue
    s=f; ref=P[s-1]
    while f+1<=630 and not isov(f+1) and ((P[f]!=ref)&M).sum()<=T: f+=1
    segs.append((s,f)); f+=1
def mode(stack):
    # per-pixel mode over axis 0
    n=stack.shape[0]
    if n==1: return stack[0], np.ones(stack.shape[1:],float)
    srt=np.sort(stack,0)
    best=srt[0].copy(); bc=np.zeros(stack.shape[1:],int); cur=srt[0].copy(); cc=np.ones(stack.shape[1:],int)
    bc[:]=1
    for i in range(1,n):
        same=srt[i]==cur
        cc=np.where(same,cc+1,1); cur=srt[i]
        upd=cc>bc; best=np.where(upd,cur,best); bc=np.where(upd,cc,bc)
    return best, bc/n
def to565(c):
    r=(c>>16)&255; g=(c>>8)&255; b=c&255
    return ((r>>3)<<11)|((g>>2)<<5)|(b>>3)
NONE=-1
layer=np.full((H,240),NONE,np.int64)
out=[]
for s,e in segs:
    rm,_=mode(P[s-1:e]); bm,_=mode(B[s-1:e])
    want=np.where((rm!=bm)&M, to565(rm), NONE)
    # isolated single pixels that differ only for codec noise: drop if ref matches base in 3x3 majority? keep simple
    d=want!=layer
    runs=[]
    for y in range(H):
        xs=np.where(d[y])[0]
        i=0
        while i<len(xs):
            x0=xs[i]; j=i
            while j+1<len(xs) and xs[j+1]==xs[j]+1: j+=1
            runs.append((y,x0,[int(v) for v in want[y,x0:xs[j]+1]])); i=j+1
    layer=want
    out.append((s,e,runs))
nv=sum(len(r[2]) for o in out for r in o[2])
print(len(segs),'segments', nv,'patch px', file=sys.stderr)
with open('hb/gp/sim/gib_v8_art.inc','w') as fo:
    fo.write('/* GENERATED by v8art.py from LOCKED/refs/game_gibson_v8@3x.mp4 (traced board art, full 240x320 outside rain windows and the plate interior).\n'
             ' * Per non-overlay segment: delta patch over the art layer. Values RGB565; -1 = no art (firmware base shows). */\n')
    vals=[]; runs=[]; segi=[]
    for s,e,rs in out:
        segi.append((s,e,len(runs)))
        for y,x,v in rs:
            runs.append((y,x,len(v),len(vals))); vals+=v
    segi.append((9999,9999,len(runs)))
    fo.write('static const int32_t V8A_VAL[%d] = {'%len(vals))
    for i,v in enumerate(vals): fo.write(('\n' if i%24==0 else '')+'%d,'%v)
    fo.write('};\nstruct V8ARun { uint16_t y, x, n; uint32_t v; };\nstatic const V8ARun V8A_RUN[%d] = {'%len(runs))
    for i,r in enumerate(runs): fo.write(('\n' if i%8==0 else '')+'{%d,%d,%d,%d},'%r)
    fo.write('};\nstruct V8ASeg { int16_t f0, f1; uint32_t r0; };\nstatic const V8ASeg V8A_SEG[%d] = {'%len(segi))
    for i,r in enumerate(segi): fo.write(('\n' if i%6==0 else '')+'{%d,%d,%d},'%r)
    fo.write('};\n')
