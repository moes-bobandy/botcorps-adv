"""Generate the port gamma LUT with C libm powf/rintf and float32 intermediates.
Run from the repository root; no Python pow() or double-precision gamma math.
"""
import ctypes
import ctypes.util
import re
from pathlib import Path

libm = ctypes.CDLL(ctypes.util.find_library("m"))
for name in ("powf", "rintf"):
    fn = getattr(libm, name)
    fn.restype = ctypes.c_float
libm.powf.argtypes = [ctypes.c_float, ctypes.c_float]
libm.rintf.argtypes = [ctypes.c_float]
f32 = lambda x: ctypes.c_float(x).value
source = Path("src/live/lv_port_data.h").read_text()
phases = re.search(r"LV_PORT_S\[42\] = \{([^}]+)", source).group(1)
gamma = f32(float(re.search(r"#define LV_PORT_GAMMA ([0-9.]+)f", source).group(1)))
rows = []
for phase in phases.split(","):
    e = f32(1.0 / f32(1.0 + f32(gamma * f32(float(phase.rstrip("f"))))))
    rows.append([int(libm.rintf(f32(255.0 * libm.powf(f32(v / 255.0), e)))) for v in range(256)])
assert len(rows) == 42 and all(0 <= v <= 255 for row in rows for v in row)
Path("src/live/lv_port_luts.h").write_text(
    "// Generated by tools/port/gen_port_luts.py using IEEE-754 float32 C libm.\n#pragma once\n"
    "static const uint8_t LV_PORT_LUTS[42][256] = {\n" +
    "".join("    {" + ",".join(map(str, row)) + "},\n" for row in rows) + "};\n")
