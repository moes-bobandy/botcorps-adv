"""mock/v1220 item 1b: generate src/live/lv_term_norain.h (TERMINALbot sub-screen board rain removed).
Input: host-sim RGB captures of the TERMINALbot sub-screen, LV_TERM_NORAIN=0 build, script per theme T = 0..5:
  tick 300 / motion 1 / theme T / page 3 / tick 10 / go 3 / tick 40 / rec 500 crT     (files DIR/crT.rgb)
Rule, in the board window between the hunt cards: every pixel that ever changes takes its most common colour; then any pixel that is
not bare board in theme 0 (black or the purple trace / via family) is rain: it takes the trace colour when a straight trace runs
through it (same colour both sides, horizontally or vertically, within 8 px), else that theme's board black. Output = RGB565 per theme
clip. Only themes 0..2 are emitted: themes 3..5 (and 6..11, which play theme 3) move whole ghost bots / name tags over a grid,
which this per-pixel rule cannot clean (it left smears), so those clips keep their background.
usage: gen_term_norain.py DIR OUT.h"""
import sys, numpy as np
D, OUT = sys.argv[1], sys.argv[2]
X0, Y0, X1, Y1 = 72, 146, 167, 255
CARDS = [(35, 145, 71, 196), (170, 145, 206, 196), (78, 200, 117, 256), (122, 200, 162, 256), (75, 30, 165, 150)]
BOARD = {(0, 0, 0), (115, 36, 165), (181, 32, 255), (90, 32, 99), (181, 109, 173)}
win = np.zeros((320, 240), bool); win[Y0:Y1 + 1, X0:X1 + 1] = True
for (a, b, c, d) in CARDS: win[b:d + 1, a:c + 1] = False
M, V = [], np.zeros((320, 240), bool)
for t in range(6):
    f = np.fromfile(f'{D}/cr{t}.rgb', np.uint8).reshape(-1, 320, 240, 3)
    p = (f[..., 0].astype(np.uint32) << 16) | (f[..., 1].astype(np.uint32) << 8) | f[..., 2]
    v = (p != p[0]).any(0) & win; V |= v
    m = p[0].copy()
    for y, x in zip(*np.nonzero(v)):
        u, c = np.unique(p[:, y, x], return_counts=True); m[y, x] = u[c.argmax()]
    M.append(m)
G = np.zeros((320, 240), bool)
for y, x in zip(*np.nonzero(win)):
    c = int(M[0][y, x]); G[y, x] = (c >> 16, (c >> 8) & 255, c & 255) not in BOARD
mask = V | G
blk0 = win & ~G & (M[0] == 0)
def fill(m, y, x):
    for dy, dx in ((0, 1), (1, 0)):
        e = []
        for s in (-1, 1):
            k = 1
            while k <= 8 and G[y + s * k * dy, x + s * k * dx]: k += 1
            e.append(None if k > 8 else (y + s * k * dy, x + s * k * dx))
        if e[0] and e[1] and m[e[0]] == m[e[1]] and M[0][e[0]] != 0: return m[e[0]]
    return None
vals = []
for t in range(3):
    m = M[t]; u, c = np.unique(m[blk0], return_counts=True); blk = u[c.argmax()]
    out = m.copy()
    for y, x in zip(*np.nonzero(G)):
        f = fill(m, y, x); out[y, x] = blk if f is None else f
    o = out[mask]; vals.append(((o >> 19) << 11) | (((o >> 10) & 63) << 5) | ((o >> 3) & 31))
ys, xs = np.nonzero(mask); X0, Y0, X1, Y1 = xs.min(), ys.min(), xs.max(), ys.max()
W = X1 - X0 + 1; nb = (W + 7) // 8; bits, off, n = [], [], 0
for y in range(Y0, Y1 + 1):
    off.append(n); row = [0] * nb
    for x in range(X0, X1 + 1):
        if mask[y, x]: row[(x - X0) // 8] |= 1 << ((x - X0) % 8); n += 1
    bits += row
L = ['/* mock/v1220 item 1b (Mobandy 4:09 PM ET 11-24 "remove that old background rain"): the TERMINALbot sub-screen board rain',
     ' * (digits + skull glyphs over the traces between the hunt cards) taken out. GENERATED by tools/livescan/gen_term_norain.py from',
     ' * host-sim captures of the locked LK_S_TERM_T0..+5 clips (500 frames each). Masked pixels in row-major bit order; RGB565 for theme',
     ' * clips 0..2 only (3..5 and the re-inked 6..11 move ghost bots over a grid: not cleanable this way, they keep their background). */',
     '#pragma once', f'#define LV_TNR_X0 {X0}', f'#define LV_TNR_Y0 {Y0}', f'#define LV_TNR_X1 {X1}', f'#define LV_TNR_Y1 {Y1}',
     f'#define LV_TNR_NB {nb}', '#define LV_TNR_NTHEME 3', f'#define LV_TNR_N {n}',
     f'static const uint8_t LV_TNR_BITS[{len(bits)}] = {{{",".join(map(str, bits))}}};',
     f'static const uint16_t LV_TNR_OFF[{len(off)}] = {{{",".join(map(str, off))}}};',
     f'static const uint16_t LV_TNR_RGB[3][{n}] = {{{",".join("{" + ",".join(map(str, v)) + "}" for v in vals)}}};']
open(OUT, 'w').write('\n'.join(L) + '\n')
print(OUT, 'masked', n, 'rain-glyph px', int(G.sum()), 'varying px', int(V.sum()), 'rect', (X0, Y0, X1, Y1))
