"""cyd_livescan clip data: the NON-GAME subset of the committed LOCKED blob.
Reads src/lock/lock_data.h + src/lock/lock_blob.bin (never re-encodes, never
reads cyd-lock-store) and keeps clips boot/home/term/scan/ctl (segments 0..20)
byte for byte. Game clips (gib + 10 device games) are left out.
Writes src/lock/live/lock_data_live.h, lock_blob_live.bin, lock_blob_live.S
(the .S carries the blob sha256 so SCons re-assembles on a new blob)."""
import re, hashlib, os, json
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
H = open(R + '/src/lock/lock_data.h').read()
blob = open(R + '/src/lock/lock_blob.bin', 'rb').read()
KEEP_CLIPS = ['boot', 'home', 'term', 'scan', 'ctl']
def arr(name):
    m = re.search(r'%s\[(\d+)\]\[2\] = \{\n(.*?)\n\};' % name, H, re.S)
    return [tuple(map(int, p)) for p in re.findall(r'\{(\d+),(\d+)\}', m.group(2))]
chunks, ops = arr('LK_CHUNK'), arr('LK_OP')
segs = [(int(a), int(b), int(c), int(d), t) for a, b, c, d, t in re.findall(r'\{(\d+),(\d+),(\d+),(\d+)\}, /\* (\w+) \*/', H)]
clips = re.findall(r'\{"(\w+)", (LK_PAL\d+), (\d+), (\d+), (\d+)\}', H)
assert [c[0] for c in clips[:5]] == KEEP_CLIPS, clips[:5]
nseg = sum(int(c[4]) for c in clips[:5])  # 21
last = segs[nseg - 1]; nop = last[0] + last[1] + (1 if last[2] else 0)
assert segs[nseg][0] == nop, 'ops of kept segs must be a prefix'
nch = ops[nop - 1][0] + ops[nop - 1][1]
assert ops[nop][0] == nch, 'chunks of kept ops must be a prefix'
cut = chunks[nch - 1][0] + chunks[nch - 1][1]
assert chunks[nch][0] == cut and all(chunks[i][0] + chunks[i][1] == chunks[i + 1][0] for i in range(nch - 1))
lb = blob[:cut]
out = ['/* GENERATED by tools/livescan/make_live_blob.py from src/lock/lock_data.h. Do not edit.',
       ' * Non-game subset of the LOCKED blob (clips %s), byte-identical prefix.' % '/'.join(KEEP_CLIPS),
       ' * blob sha256 %s, %d bytes. */' % (hashlib.sha256(lb).hexdigest(), cut),
       '#pragma once', '#include <stdint.h>', '#define LK_BLOB_SIZE %du' % cut,
       'static const uint32_t LK_CHUNK[%d][2] = {' % nch, ','.join('{%d,%d}' % c for c in chunks[:nch]), '};',
       'static const uint16_t LK_OP[%d][2] = {' % nop, ','.join('{%d,%d}' % o for o in ops[:nop]), '};',
       'struct LkSeg { uint16_t op0, n; uint8_t loop; uint16_t f0; };',
       'static const LkSeg LK_SEG[%d] = {' % nseg]
out += ['  {%d,%d,%d,%d}, /* %s */' % s for s in segs[:nseg]] + ['};']
for c in clips[:5]:
    m = re.search(r'static const uint16_t %s\[\d+\] = \{[^}]*\};' % c[1], H); out.append(m.group(0))
out.append('struct LkClip { const char *name; const uint16_t *pal; uint16_t npal, seg0, nseg; };')
out.append('static const LkClip LK_CLIP[5] = {')
out += ['  {"%s", %s, %s, %s, %s},' % c for c in clips[:5]] + ['};']
for i, c in enumerate(clips[:5]): out.append('#define LK_C_%s %d' % (c[0].upper(), i))
for i, s in enumerate(segs[:nseg]): out.append('#define LK_S_%s %d' % (s[4].upper(), i))
D = R + '/src/lock/live/'
open(D + 'lock_data_live.h', 'w').write('\n'.join(out) + '\n')
open(D + 'lock_blob_live.bin', 'wb').write(lb)
sha = hashlib.sha256(lb).hexdigest()
open(D + 'lock_blob_live.S', 'w').write("""/* GENERATED by tools/livescan/make_live_blob.py. Non-game LOCKED clip blob, flash rodata.
 * blob sha256 %s, %d bytes. Only assembled for BOTCORPS_CYD_LIVESCAN (cyd_livescan). */
#if defined(BOTCORPS_CYD_LIVESCAN) && BOTCORPS_CYD_LIVESCAN
    .section .rodata.lk_blob_live
    .global lk_blob_live
    .balign 4
lk_blob_live:
    .incbin "src/lock/live/lock_blob_live.bin"
    .global lk_blob_live_end
lk_blob_live_end:
#endif
""" % (sha, cut))
json.dump({'from_blob_sha256': hashlib.sha256(blob).hexdigest(), 'bytes': cut, 'sha256': sha, 'clips': KEEP_CLIPS,
           'segs': nseg, 'ops': nop, 'chunks': nch, 'dropped_bytes': len(blob) - cut}, open(D + 'lock_blob_live.json', 'w'), indent=1)
print('live blob', cut, 'of', len(blob), 'sha', sha, 'segs', nseg, 'ops', nop, 'chunks', nch)
