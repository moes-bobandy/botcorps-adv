void botcorps_glyph_blit(lgfx::LovyanGFX &dst, int x, int y, int id,
                         uint8_t c1, uint8_t c2, uint8_t c3,
                         bool (*allow)(int px, int py))
{
    if (id < 0 || id >= BOTCORPS_ICON_N) id = BOTCORPS_ICON_UNKNOWN;
    const uint8_t pal[4] = { 0, c1, c2, c3 };
    const uint8_t *rowp = GLYPH[id];
    for (int row = 0; row < 12; ++row) {
        for (int col = 0; col < 12; ++col) {
            const int px = x + col;
            const int py = y + row;
            if (allow && !allow(px, py)) continue;
            const int bit = col * 2;
            const uint8_t byte = pgm_read_byte(rowp + (bit >> 3));
            const int shift = 6 - (bit & 7);
            const int ix = (byte >> shift) & 3;
            if (ix) botcorps_pal_pixel(dst, px, py, pal[ix]);
        }
        rowp += 3;
    }
}
