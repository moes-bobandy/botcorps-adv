#!/usr/bin/env python3
"""CALbot touch-cal art -> src/live/lv_calbot_art.h  (the board layout from the approved reference, not a guess).

Source refs (the user's approved CALbot design, kept in cyd-lock-store LOCKED/refs/calbot/):
  229cd344...f5b2.gif  lime CALbot cal flow, 3x, 100 ms/frame, frames 0..126 = CALbot (127+ = BOOTbot)
  b0a422d0...8f81.png  approved CAL OK end frame (label "CALbot"; the GIF frames spell it "CALBOT")
Every GIF frame gets b0a422d0's label pixels (x121-130 y169-173, the lowercase "bot") so the chip says CALbot.

Output: a 41-colour palette, the OK frame as the base image (row-indexed RLE), and per-element variants
(RLE over the element rect, 255 = transparent: pixels that never change in the reference). The firmware picks a
variant per element from the cal state + time since CALbot opened (same 100 ms beat as the reference). The
terminal lines are NOT art: they are drawn live in glcd 5x7 (the font the reference uses).
  make_calbot_art.py [refs_dir] [out.h]"""
import sys, os
import numpy as np
from PIL import Image, ImageSequence

REFS = '/workspace/cyd-lock-store/LOCKED/refs/calbot'
OUT = 'src/live/lv_calbot_art.h'
GIF = '229cd34455f4d157af647360fe380a2e3ca959c83e2d66a7edd33500c1d9f5b2.gif'
OKP = 'b0a422d0eecc368ae2dda7e2b025b4190d38d8ab9b71deb0a72e50849d8b8f81.png'
NF = 127

def load_frames():
    ok = np.asarray(Image.open(os.path.join(REFS, OKP)).convert('RGB'))[1::3, 1::3].astype(np.int16)
    fr = []
    for i, im in enumerate(ImageSequence.Iterator(Image.open(os.path.join(REFS, GIF)))):
        if i >= NF: break
        a = np.asarray(im.convert('RGB'))[1::3, 1::3].astype(np.int16).copy()
        a[169:174, 121:131] = ok[169:174, 121:131]          # CALBOT -> CALbot
        fr.append(a)
    return np.stack(fr), ok

# element: name -> (x0, y0, x1, y1 inclusive, [source frame per variant])
# chips in capture order: 1 TOP LEFT, 2 TOP RIGHT, 3 BOTTOM RIGHT, 4 BOTTOM LEFT (as the reference flow)
CH_LOCK = [39, 64, 89, 114]                 # frame the chip locks (= next prompt / OK)
CH_HOLD0 = [24, 49, 74, 99]                 # first "holding" frame of the full 1.5 s hold
def phase_b(f):                             # face bob: 900 ms period, B half first seen at frame 7
    return ((f + 2) // 9) & 1

def elements():
    E = []
    E.append(('ctr', (100, 116, 136, 152), [0, 7]))                         # A, B (face bob)
    FACE = [(41, 40, 62, 62), (176, 40, 197, 62), (176, 211, 197, 233), (41, 211, 62, 233)]
    ANT = [(38, 31, 65, 35), (173, 31, 200, 35), (173, 202, 200, 206), (38, 202, 65, 206)]
    LBL = [(41, 73, 63, 77), (176, 73, 198, 77), (176, 244, 198, 248), (41, 244, 63, 248)]
    TR = [(72, 55, 100, 96), (136, 55, 168, 96), (136, 188, 168, 229), (72, 188, 100, 229)]
    for i in range(4):
        lit = range(0 if i == 0 else CH_LOCK[i - 1], NF)
        on_a = next(f for f in lit if not phase_b(f))  # lit, phase A
        on_b = next(f for f in lit if phase_b(f))      # lit, phase B
        pend = (0, 7) if i else (0, 7)                 # chip 1 is never shown pending: reuse its lit art
        E.append((f'face{i+1}', FACE[i], [pend[0], pend[1], on_a, on_b]))
        E.append((f'ant{i+1}', ANT[i], [0] + list(range(CH_HOLD0[i], CH_HOLD0[i] + 14)) + [CH_LOCK[i] - 1]))
        E.append((f'lbl{i+1}', LBL[i], [0, CH_LOCK[i], CH_LOCK[i] + 2]))
        dim = 0 if i == 0 else CH_LOCK[i - 1] + 1
        bri = 3 if i == 0 else CH_LOCK[i - 1]
        E.append((f'tr{i+1}', TR[i], [0, dim, bri] + list(range(CH_HOLD0[i], CH_HOLD0[i] + 14)) + [CH_LOCK[i]]))
    E.append(('status', (100, 176, 138, 180), [0] + CH_LOCK))                # CAL 0..3 OF 4, CAL OK
    for k, (y, f) in enumerate([(103, 12), (117, 16), (131, 20), (173, 32), (187, 36)]):
        E.append((f'pin{k+1}', (227, y, 233, y + 5), [0, f]))
    for k, (x, f) in enumerate([(85, 8), (111, 12), (137, 4), (163, 4)]):
        E.append((f'tab{k+1}', (x, 264, x + 6, 269), [0, f]))
    E.append(('cursor', (120, 296, 175, 303), [0, 2]))                       # off, on
    return E

def main():
    F, ok = load_frames()
    assert len(F) == NF and (F[122] == ok).all(), 'frame 122 must be the approved OK frame'
    cols = np.unique(np.concatenate([F.reshape(-1, 3), ok.reshape(-1, 3)]), axis=0)
    assert len(cols) < 255
    key = lambda a: (a[..., 0].astype(np.int64) << 16) | (a[..., 1].astype(np.int64) << 8) | a[..., 2]
    ck = key(cols); lut = {int(v): i for i, v in enumerate(ck)}
    def idx(a): return np.vectorize(lambda v: lut[int(v)])(key(a)).astype(np.uint8)
    out = []
    P = lambda s: out.append(s)
    P('/* GENERATED by tools/livescan/make_calbot_art.py from the approved CALbot refs - do not edit.')
    P(f' * {GIF} (frames 0..{NF-1}, label patched to CALbot) + {OKP} */')
    P('#pragma once\n#include <stdint.h>')
    pal = ', '.join('0x%04x' % (((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)) for r, g, b in cols.astype(int).tolist())
    P(f'static const uint16_t LVC_PAL[{len(cols)}] = {{{pal}}};')
    def rle(ix, mask=None):
        flat = ix.reshape(-1).astype(int).copy()
        if mask is not None: flat[~mask.reshape(-1)] = 255
        o = []; k = 0
        while k < len(flat):
            v = flat[k]; n = 1
            while k + n < len(flat) and flat[k + n] == v and n < 255: n += 1
            o += [n, v]; k += n
        return o
    # base: one RLE stream per row (runs never cross rows), plus row start offsets
    bi = idx(ok); data = []; rows = []
    for y in range(320): rows.append(len(data)); data += rle(bi[y])
    P(f'static const uint32_t LVC_BASE_ROW[320] = {{{", ".join(map(str, rows))}}};')
    P(f'static const uint8_t LVC_BASE[{len(data)}] = {{{", ".join(map(str, data))}}};')
    E = elements(); blob = []; meta = []; voffs = []
    for name, (x0, y0, x1, y1), src in E:
        sub = F[:, y0:y1 + 1, x0:x1 + 1]
        mask = (sub != sub[0:1]).any(3).any(0)
        first = len(voffs)
        for f in src:
            voffs.append(len(blob)); blob += rle(idx(F[f, y0:y1 + 1, x0:x1 + 1]), mask)
        meta.append((name, x0, y0, x1, y1, first, len(src)))
    voffs.append(len(blob))
    P(f'static const uint8_t LVC_VAR[{len(blob)}] = {{{", ".join(map(str, blob))}}};')
    P(f'static const uint32_t LVC_VOFF[{len(voffs)}] = {{{", ".join(map(str, voffs))}}};')
    P('struct LvcElem { int16_t x0, y0, x1, y1; uint16_t v0, nv; };')
    P(f'static const LvcElem LVC_EL[{len(meta)}] = {{')
    for name, x0, y0, x1, y1, v0, nv in meta: P(f'    {{{x0}, {y0}, {x1}, {y1}, {v0}, {nv}}},  /* {name} */')
    P('};')
    P('enum { ' + ', '.join(f'LVC_E_{m[0].upper()}' for m in meta) + f', LVC_NE }};')
    rule = []
    for i in range(NF):
        ys = [y for y in range(270, 300) if tuple(F[i, y, 37]) == (90, 36, 99)]
        rule.append(ys[0] if ys else 0)
    P(f'/* terminal scan rule row per 100 ms beat (reference frames 0..{NF-1}), repeats */')
    P(f'static const uint16_t LVC_RULE[{NF}] = {{{", ".join(map(str, rule))}}};')
    P('#define LVC_INK 0x%04x   /* terminal text (181,255,255) */' % (((181 >> 3) << 11) | ((255 >> 2) << 5) | (255 >> 3)))
    P('#define LVC_RULE_C 0x%04x /* scan rule (90,36,99) */' % (((90 >> 3) << 11) | ((36 >> 2) << 5) | (99 >> 3)))
    open(OUT, 'w').write('\n'.join(out) + '\n')
    print(f'{OUT}: pal {len(cols)}, base {len(data)} B, variants {len(blob)} B, {len(meta)} elements, {len(voffs)-1} variants')

if __name__ == '__main__':
    if len(sys.argv) > 1: REFS = sys.argv[1]
    if len(sys.argv) > 2: OUT = sys.argv[2]
    main()
