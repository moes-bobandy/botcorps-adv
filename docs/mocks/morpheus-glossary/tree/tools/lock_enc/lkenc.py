"""Encode locked clips into firmware data: src/lock/lock_data.h + src/lock/lock_blob.bin.
Each clip: own palette (<=255 RGB565). Each segment: keyframe op, delta ops, optional loop-back op.
An op is a list of raw-deflate chunks; each chunk inflates to <=16 KB of records: u16 y, u8 x, u8 n, n index bytes."""
import sys, os, zlib, struct, json, numpy as np
sys.path.insert(0,os.path.dirname(os.path.abspath(__file__))); import clip
TH=30; CH=16384
def frames(p):
    cache='/workspace/cydport/cache/'+os.path.basename(p)+'.npy'
    if os.path.exists(cache): return np.load(cache,mmap_mode='r')
    fr=clip.load(p); np.save(cache,fr); return fr
def build_palette(fr, maxn=255, merge=20):
    q=(np.asarray(fr[::2]).reshape(-1,3)//4).astype(np.int32)
    key=(q[:,0]<<12)|(q[:,1]<<6)|q[:,2]
    u,c=np.unique(key,return_counts=True)
    pal=[]
    for k in u[np.argsort(-c)]:
        col=np.array([(k>>12)*4+2,((k>>6)&63)*4+2,(k&63)*4+2])
        if pal and np.abs(np.array(pal)-col).max(1).min()<=merge: continue
        pal.append(col)
        if len(pal)>=maxn: break
    pal=np.array(pal,np.int32)
    # LUT over 6-bit cube
    g=np.stack(np.meshgrid(np.arange(64),np.arange(64),np.arange(64),indexing='ij'),-1).reshape(-1,3)*4+2
    best=np.zeros(len(g),np.int32); bd=np.full(len(g),1<<30)
    for i,c in enumerate(pal):
        d=((g-c)**2).sum(1); m=d<bd; bd[m]=d[m]; best[m]=i
    return pal, best.astype(np.uint8)
def idx_of(lut,f):
    q=(f.astype(np.int32)//4); return lut[(q[...,0]<<12)|(q[...,1]<<6)|q[...,2]]
def records(chg, shown):
    out=[]
    for y in np.nonzero(chg.any(1))[0]:
        r=np.nonzero(chg[y])[0]; s=p=r[0]; segs=[]
        for x in r[1:]:
            if x-p<=3: p=x; continue
            segs.append((s,p)); s=p=x
        segs.append((s,p))
        for s,e in segs:
            while s<=e:
                n=min(e-s+1,255); out.append(struct.pack('<HBB',int(y),int(s),n)+bytes(shown[y,s:s+n].astype(np.uint8))); s+=n
    return out
def chunks(recs):
    cs=[]; cur=b''
    for r in recs:
        if len(cur)+len(r)>CH-4: cs.append(cur); cur=b''
        cur+=r
    cs.append(cur)
    return [zlib.compress(c+b'\xff\xff\x00\x00',9)[2:-4] for c in cs]   # raw deflate
class Enc:
    def __init__(s): s.blob=bytearray(); s.chunks=[]; s.ops=[]; s.segs=[]; s.clips=[]; s.pals=[]; s.shown={}
    def op(s, recs):
        first=len(s.chunks)
        for c in chunks(recs): s.chunks.append((len(s.blob),len(c))); s.blob+=c
        s.ops.append((first,len(s.chunks)-first)); return len(s.ops)-1
    def clip(s, name, path, segs):
        fr=frames(path); pal,lut=build_palette(fr)
        palc=pal.astype(np.int32); seg0=len(s.segs)
        for (a,b,loop,tag) in segs:
            key=idx_of(lut,fr[a]); shown=key.copy()
            op0=s.op(records(np.ones((320,240),bool),shown))

            for f in range(a+1,b+1):
                fi=np.asarray(fr[f]); idx=idx_of(lut,fi)
                dist=np.abs(palc[shown]-fi.astype(np.int32)).max(2)
                chg=(dist>TH)&(idx!=shown); shown=np.where(chg,idx,shown)

                s.op(records(chg,shown))
            if loop:
                chg=shown!=key; s.op(records(chg,key))
            s.segs.append((op0,b-a+1,1 if loop else 0,a,tag))
        s.clips.append((name,len(s.pals),seg0,len(segs)))
        s.pals.append(pal)
        return pal
    def write(s, hdr, binp, meta):
        open(binp,'wb').write(s.blob)
        L=[]; w=L.append
        w('/* GENERATED by tools/lkenc.py from the LOCKED clips. Do not edit. */')
        w('#pragma once\n#include <stdint.h>')
        w('#define LK_BLOB_SIZE %du'%len(s.blob))
        w('static const uint32_t LK_CHUNK[%d][2] = {'%len(s.chunks)); w(','.join('{%d,%d}'%c for c in s.chunks)+'};')
        w('static const uint16_t LK_OP[%d][2] = {'%len(s.ops)); w(','.join('{%d,%d}'%o for o in s.ops)+'};')
        w('struct LkSeg { uint16_t op0, n; uint8_t loop; uint16_t f0; };')
        w('static const LkSeg LK_SEG[%d] = {'%len(s.segs))
        for (op0,n,lp,a,tag) in s.segs: w('  {%d,%d,%d,%d}, /* %s */'%(op0,n,lp,a,tag))
        w('};')
        for i,p in enumerate(s.pals):
            v=[((c[0]>>3)<<11)|((c[1]>>2)<<5)|(c[2]>>3) for c in p]
            w('static const uint16_t LK_PAL%d[%d] = {%s};'%(i,len(v),','.join('0x%04x'%x for x in v)))
        w('struct LkClip { const char *name; const uint16_t *pal; uint16_t npal, seg0, nseg; };')
        w('static const LkClip LK_CLIP[%d] = {'%len(s.clips))
        for (n,pi,s0,ns) in s.clips: w('  {"%s", LK_PAL%d, %d, %d, %d},'%(n,pi,len(s.pals[pi]),s0,ns))
        w('};')
        for i,(n,pi,s0,ns) in enumerate(s.clips): w('#define LK_C_%s %d'%(n.upper(),i))
        for i,(op0,n,lp,a,tag) in enumerate(s.segs): w('#define LK_S_%s %d'%(tag.upper(),i))
        open(hdr,'w').write('\n'.join(L)+'\n')
        json.dump(meta,open(binp+'.json','w'),indent=1)
