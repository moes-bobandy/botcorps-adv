/* Port layer: three LOCKED mocks on the live clip screens, without touching the locked clip blob.
 *   HOME  ui_home_tap_glow (variant O)  - MORPHEUS chip (replaces the grey BOOTbot chip), CONTROL chip + TERMINAL-style pins,
 *         GIBSON chip (shaded cream face, small pins, main-bot rain) and the breathing face glow on MORPHEUS / CONTROL /
 *         GIBSON / SCAN / TERMINAL (lift + ring, AMAX 0.8, 7 px, 1.4 s).
 *   SCAN  ui_main_bot_rain SCANbot chip (black-body rain, one-line label) + ui_scan_glow: WIFI face orange / BT face blue
 *         (face-only tint, bezel / label / pins / ring stay grey) and the halo-only glow on WIFI / BLE / GIB (AMAX 1.0, 9 px, 1.4 s).
 *   TERM  ui_main_bot_rain TERMINALbot chip (black-body rain, one-line label).
 * Data: lv_port_data.h, generated by tools/port/gen_port.py from the locks. Every owned pixel carries a code:
 *   1 static palette colour, 2 rain slot (10 steps), 3 glow slot (lift / ring / face tint over its own base or over the clip
 *   pixel underneath, captured as the clip draws it). Themes 0..5 carry per-theme colours mapped from the clip itself (the
 *   locked theme 2 keeps the lock's exact value); 6..11 take theme 3 + the usual cyan re-ink.
 * Cost: the clip path only substitutes owned pixels. Motion repaints only the pixels that change: rain runs when the rain
 * step changes (140 ms), glow runs when the 30 fps glow phase changes, nothing else. BG MOTION OFF freezes both. */
#pragma once
#include <math.h>
struct LvPortReg { int16_t x0, y0, x1, y1; const uint16_t *code; };
struct LvPortGlow { float a; uint16_t base; uint16_t acc; uint8_t op; };   /* op 0 lift, 1 ring, 2 face tint; base 0xFFFF = clip px */
struct LvPortRun { uint16_t y; uint8_t x, n; };
struct LvPortScr { const LvPortReg *reg; uint8_t nreg; const uint16_t (*rain)[10]; const LvPortGlow *glow; uint16_t nglow;
                   const LvPortRun *rr; uint16_t nrr; const LvPortRun *gr; uint16_t ngr; };
#include "lv_port_data.h"
#include "lv_port_luts.h"
static int lv_port_sc = -1;                       /* LV_PORT_SCR index for the current screen, -1 none */
static uint32_t lv_port_t0 = 0;                   /* screen entry: rain + glow clock */
static int lv_port_n = 0, lv_port_step = LV_PORT_RAIN_T0 % 10;   /* glow phase / rain step currently on the panel */
static int lv_port_lutn = -1; static uint8_t lv_port_lut[256];
static uint16_t *lv_port_under = nullptr;   /* heap, allocated once (static did not fit dram0_0_seg); none: glows stay still */
static void lv_port_begin(void)
{
    lv_port_sc = lv_scr == LV_SC_HOME ? 0 : lv_scr == LV_SC_SCAN ? 1 : lv_scr == LV_SC_TERM ? 2 : -1;
    lv_port_t0 = lv_now; lv_port_n = 0; lv_port_step = LV_PORT_RAIN_T0 % 10;
    if (!lv_port_under) lv_port_under = (uint16_t *)malloc(LV_PORT_MAXGLOW * sizeof(uint16_t));
    if (lv_port_under) memset(lv_port_under, 0, LV_PORT_MAXGLOW * sizeof(uint16_t));
}
static inline uint16_t lv_port_code(int x, int y)
{
    const LvPortScr &P = LV_PORT_SCR[lv_port_sc];
    for (int r = 0; r < P.nreg; ++r) {
        const LvPortReg &R = P.reg[r];
        if (x >= R.x0 && x <= R.x1 && y >= R.y0 && y <= R.y1) return R.code[(y - R.y0) * (R.x1 - R.x0 + 1) + (x - R.x0)];
    }
    return 0;
}
static bool lv_port_row(int y, int x, int n)      /* does [x, x+n) on row y touch a port region? */
{
    if (lv_port_sc < 0) return false;
    const LvPortScr &P = LV_PORT_SCR[lv_port_sc];
    for (int r = 0; r < P.nreg; ++r) { const LvPortReg &R = P.reg[r]; if (y >= R.y0 && y <= R.y1 && R.x1 >= x && R.x0 < x + n) return true; }
    return false;
}
static inline uint32_t lv_port_x888(uint16_t c) { const uint32_t r = c >> 11, g = (c >> 5) & 63, b = c & 31; return (r << 3 | r >> 2) << 16 | (g << 2 | g >> 4) << 8 | (b << 3 | b >> 2); }
static uint32_t lv_port_rgb(uint16_t i, int x, int y)
{
    const uint32_t v = LV_PORT_PAL[i][lv_theme < LV_THEME_ORIG ? lv_theme : LV_THEME_BASE];
    if (LV_PORT_PTHEMED[i] && lv_reink_on()) return lv_port_x888(lv_multi_ink(lv_hex(v), x, y));
    return v;
}
static void lv_port_mklut(void)
{
    if (lv_port_lutn == lv_port_n) return;
    lv_port_lutn = lv_port_n;
    memcpy(lv_port_lut, LV_PORT_LUTS[lv_port_n], sizeof lv_port_lut);
}
static uint16_t lv_port_glow(const LvPortGlow &G, uint32_t c, int x, int y)
{
    const int R = (c >> 16) & 255, Gc = (c >> 8) & 255, B = c & 255;
    if (G.op == 0) { lv_port_mklut(); return lv_rgb(lv_port_lut[R], lv_port_lut[Gc], lv_port_lut[B]); }
    const uint32_t a = lv_port_rgb(G.acc, x, y);
    if (G.op == 2) {                              /* face tint: COL * L / L_MID, L = (3R+6G+B)/10, L_MID 116 -> COL*(3R+6G+B)/1160, half-even */
        const int L = R * 3 + Gc * 6 + B; int o[3];
        for (int k = 0; k < 3; ++k) {
            const int q = (int)((a >> (16 - 8 * k)) & 255) * L; int v = (q + 580) / 1160;
            if ((q + 580) % 1160 == 0 && (v & 1)) --v;
            o[k] = v > 255 ? 255 : v;
        }
        return lv_rgb((uint8_t)o[0], (uint8_t)o[1], (uint8_t)o[2]);
    }
    const float A = G.a * LV_PORT_S[lv_port_n], iA = 1.f - A; int o[3];
    const int cc[3] = {R, Gc, B};
    for (int k = 0; k < 3; ++k) { const float v = rintf((float)cc[k] * iA + (float)((a >> (16 - 8 * k)) & 255) * A); o[k] = v < 0 ? 0 : v > 255 ? 255 : (int)v; }
    return lv_rgb((uint8_t)o[0], (uint8_t)o[1], (uint8_t)o[2]);
}
/* the port pixel for code k over clip pixel c (RGB565, already re-inked) */
static uint16_t lv_port_px(uint16_t k, uint16_t c, int x, int y)
{
    const LvPortScr &P = LV_PORT_SCR[lv_port_sc];
    const uint16_t s = k & 16383;
    switch (k >> 14) {
    case 1: return lv_hex(lv_port_rgb(s, x, y));
    case 2: return lv_hex(lv_port_rgb(P.rain[s][lv_port_step], x, y));
    case 3: {
        const LvPortGlow &G = P.glow[s];
        if (G.base == 0xFFFF) { if (lv_port_under) lv_port_under[s] = c; return lv_port_glow(G, lv_port_x888(c), x, y); }
        return lv_port_glow(G, lv_port_rgb(G.base, x, y), x, y);
    }
    }
    return c;
}
static inline uint16_t lv_port_apply(uint16_t c, int x, int y)
{
    if (lv_port_sc < 0) return c;
    const uint16_t k = lv_port_code(x, y);
    return k ? lv_port_px(k, c, x, y) : c;
}
/* motion: repaint only the runs whose pixels change, through the same tint transform / press flash the clip path uses */
static void lv_port_runs(const LvPortRun *rn, int nr)
{
    static uint16_t lb[240];
    const LvPortScr &P = LV_PORT_SCR[lv_port_sc];
    const bool fl = lv_flash_r.x1 >= lv_flash_r.x0;
    for (int i = 0; i < nr; ++i) {
        const int y = rn[i].y, x0 = rn[i].x, n = rn[i].n;
        int tl[LV_MAXT], nt = 0;
        for (int t = 0; t < lv_ntint; ++t) if (y >= lv_tints[t].r.y0 && y <= lv_tints[t].r.y1 && lv_tints[t].r.x1 >= x0 && lv_tints[t].r.x0 < x0 + n) tl[nt++] = t;
        for (int k = 0; k < n; ++k) {
            const int x = x0 + k; const uint16_t c = lv_port_code(x, y);
            const uint16_t u = (c >> 14) == 3 ? lv_port_under[c & 16383] : 0;
            uint16_t v = lv_port_px(c, u, x, y);
            for (int j = 0; j < nt; ++j) {
                const LvRect &r = lv_tints[tl[j]].r;
                if (x < r.x0 || x > r.x1) continue;
                const LvTS s = lv_tint_state(lv_tints[tl[j]].id);
                if (!s.deco) { v = lv_tx(s, v, x, y); if (fl && lv_in(lv_flash_r, x, y)) v = lv_hi(v); }
                break;
            }
            lb[k] = v;
        }
        lv_blit(x0, y, n, 1, lb);
    }
    (void)P;
}
static void lv_port_tick(void)
{
    if (lv_port_sc < 0 || lv_play.shown < 0 || !lv_motion) return;
    const LvPortScr &P = LV_PORT_SCR[lv_port_sc];
    const uint32_t ms = lv_now - lv_port_t0;
    const int n = (int)((uint64_t)ms * 30 / 1000 % 42), st = (int)((LV_PORT_RAIN_T0 + ms / 140) % 10);
    if (st != lv_port_step) { lv_port_step = st; lv_port_runs(P.rr, P.nrr); }
    if (n != lv_port_n && lv_port_under) { lv_port_n = n; lv_port_runs(P.gr, P.ngr); }
}
