import math, struct
def f32(x): return struct.unpack('f', struct.pack('f', x))[0]
def fmt(v):
    r = repr(f32(v))
    if 'e' not in r and '.' not in r: r += '.0'
    return r + 'f'
def arr(name, vals, per=8):
    rows = ['    ' + ', '.join(fmt(v) for v in vals[i:i + per]) + ',' for i in range(0, len(vals), per)]
    return 'static const float %s[%d] = {\n%s\n};\n' % (name, len(vals), '\n'.join(rows))
SN = 1024
val, sat = [], []
for i in range(258):
    L = float(min(i, 255)); x = L / 230.0
    val.append(min(0.10 + 0.90 * x * math.sqrt(x), 1.0)); sat.append(0.88 - 0.6 * x * x * x)
out = '/* GENERATED by tools/gen_lv_lb_tables.py (v1.2.26): const tables for lv_lb_metal, in flash (DROM), not DRAM. */\n#pragma once\n#define LV_LB_SN %d\n' % SN
out += arr('lv_lb_sin_t', [math.sin(i * (6.2831853 / SN)) for i in range(SN + 1)])
out += arr('lv_lb_cuv', [math.cos((i - 70.0) * 0.045) for i in range(220)])
out += arr('lv_lb_su', [math.sin(i * 0.21) for i in range(110)])
out += arr('lv_lb_vv', [20.0 * (i / 110.0) for i in range(110)])
out += arr('lv_lb_val_t', val) + arr('lv_lb_sat_t', sat)
open('src/live/pager/lv_pager_lbtab.h', 'w').write(out)
