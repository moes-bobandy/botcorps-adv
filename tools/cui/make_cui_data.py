#!/usr/bin/env python3
"""fw-3locks-1116: pack the LOCKED CONTROLbot Color UI v6 frames (585810c / a87fe22, v6-cyd-ticker/stills/NN_*@1x.png, 24 themes in the
locked order) into src/live/cui/lv_cui_data.h for the firmware. Each frame -> RGB565 (panel format: r>>3, g>>2, b>>3), the ticker
rect (y1..23, x1..238) zeroed (the live tinted lv_scene_ticker owns it), then 20 strips of 16 rows, each raw-deflated (level 9,
wbits -15: ROM tinfl on the CYD, zlib raw inflate in the sim). Pixels are taken as-is from the locked PNGs; nothing is redrawn.
usage: make_cui_data.py <stills_dir> <out.h>"""
import sys, glob, os, zlib, hashlib
import numpy as np
from PIL import Image
SD, OUT = sys.argv[1], sys.argv[2]
files = sorted(f for f in glob.glob(os.path.join(SD, '[0-2][0-9]_*@1x.png')))
assert len(files) == 24, files
blob = bytearray(); offs = [0]; names = []
for f in files:
    a = np.array(Image.open(f).convert('RGB')).astype(np.uint32)
    assert a.shape == (320, 240, 3), (f, a.shape)
    v = (((a[..., 0] >> 3) << 11) | ((a[..., 1] >> 2) << 5) | (a[..., 2] >> 3)).astype('<u2')
    v[1:24, 1:239] = 0
    for y in range(0, 320, 16):
        c = zlib.compressobj(9, zlib.DEFLATED, -15); z = c.compress(v[y:y + 16].tobytes()) + c.flush()
        blob += z; offs.append(len(blob))
    names.append(os.path.basename(f))
with open(OUT, 'w') as o:
    o.write('/* GENERATED by tools/cui/make_cui_data.py from the LOCKED CONTROLbot Color UI v6 stills (do not edit).\n')
    for n, f in zip(names, files): o.write(' *   %s sha256 %s\n' % (n, hashlib.sha256(open(f, 'rb').read()).hexdigest()))
    o.write(' */\n#pragma once\n#define LV_CUI_N 24\n#define LV_CUI_STRIP 16\n#define LV_CUI_NSTRIP 20\n')
    o.write('static const uint32_t LV_CUI_OFF[%d] = {%s};\n' % (len(offs), ','.join(map(str, offs))))
    o.write('static const uint8_t LV_CUI_Z[%d] = {\n' % len(blob))
    for i in range(0, len(blob), 32): o.write(','.join(str(b) for b in blob[i:i + 32]) + ',\n')
    o.write('};\n')
print('frames', len(files), 'bytes', len(blob))
